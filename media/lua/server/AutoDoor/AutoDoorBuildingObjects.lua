ISAutoFenceGate = ISBuildingObject:derive("ISAutoFenceGate")

function ISAutoFenceGate:create(x, y, z, north, sprite)
    local cell = getWorld():getCell()
    self.sq = cell:getGridSquare(x, y, z)
    if not self.sq then return end
    if self:partExists(self.sq) then return end
    local spriteName = north and self.style.northSprite or self.style.sprite
    self.javaObject = IsoDoor.new(cell, self.sq, spriteName, north)
    buildUtil.setInfo(self.javaObject, self)
    self.javaObject:setMaxHealth(self:getHealth())
    self.javaObject:setHealth(self.javaObject:getMaxHealth())
    local isMetal = self.style.skill == "MetalWelding"
    self.javaObject:setBreakSound(isMetal and "MetalGateBreak" or "WoodGateBreak")
    self.sq:AddSpecialObject(self.javaObject)
    buildUtil.consumeMaterial(self)
    AutoDoor.grantAccessories(getSpecificPlayer(self.player), self.keyId)
    self.javaObject:getModData().autoDoor = true
    self.javaObject:setKeyId(self.keyId)
    self.javaObject:transmitCompleteItemToClients()
end

function ISAutoFenceGate:partExists(square)
    if not square then return false end
    local spriteName = self.north and self.style.northSprite or self.style.sprite
    local objects = square:getSpecialObjects()
    for i = 1, objects:size() do
        local object = objects:get(i - 1)
        if instanceof(object, "IsoDoor") and
            object:getNorth() == self.north and
            not object:IsOpen() and
            object:getSprite() and object:getSprite():getName() == spriteName then
            return true
        end
    end
    return false
end

function ISAutoFenceGate:isValid(square)
    if not self:haveMaterial(square) then return false end
    if not square:hasFloor(self.north) then return false end
    if square:isVehicleIntersecting() then return false end
    if not self:partExists(square) and not square:isFreeOrMidair(false) then
        return false
    end
    if buildUtil.stairIsBlockingPlacement(square, true, self.north) then return false end
    return true
end

function ISAutoFenceGate:render(x, y, z, square)
    if self:partExists(square) then return end
    local spriteName = self.north and self.style.northSprite or self.style.sprite
    local sprite = IsoSprite.new()
    sprite:LoadSingleTexture(spriteName)
    if self:isValid(square) then
        sprite:RenderGhostTile(x, y, z)
    else
        sprite:RenderGhostTileRed(x, y, z)
    end
end

function ISAutoFenceGate:getHealth()
    return self.style.health
end

function ISAutoFenceGate:new(styleIndex)
    local o = {}
    setmetatable(o, self)
    self.__index = self
    o:init()
    o.style = AutoDoor.FENCE_GATE_STYLES[styleIndex]
    o:setSprite(o.style.sprite)
    o.northSprite = o.style.northSprite
    o.isDoor = true
    o.isWallLike = true
